from abc import ABC, abstractmethod
from typing import Optional


class Стол(ABC):
    """
    Абстрактный класс, описывающий стол.
    """

    def __init__(self, материал: str, высота: float, площадь: float):
        """
        Инициализация объекта Стол.

        :param материал: Материал, из которого сделан стол.
        :param высота: Высота стола в метрах.
        :param площадь: Площадь поверхности стола в квадратных метрах.

        :Пример:
        >>> стол = ДеревянныйСтол("дерево", 0.75, 1.5)
        >>> стол.материал
        'дерево'
        """
        if высота <= 0:
            raise ValueError("Высота должна быть положительным числом.")
        if площадь <= 0:
            raise ValueError("Площадь должна быть положительным числом.")

        self.материал = материал
        self.высота = высота
        self.площадь = площадь

    @abstractmethod
    def выдержать_вес(self, вес: float) -> bool:
        """
        Проверяет, может ли стол выдержать заданный вес.

        :param вес: Вес в килограммах.
        :return: True, если стол выдержит вес, иначе False.

        :Пример:
        >>> стол = ДеревянныйСтол("дерево", 0.75, 1.5)
        >>> стол.выдержать_вес(50)
        True
        """
        ...

    @abstractmethod
    def изменить_высоту(self, новая_высота: float) -> None:
        """
        Изменяет высоту стола.

        :param новая_высота: Новая высота стола в метрах.
        :return: None

        :Пример:
        >>> стол = ДеревянныйСтол("дерево", 0.75, 1.5)
        >>> стол.изменить_высоту(0.8)
        >>> стол.высота
        0.8
        """
        ...


class ДеревянныйСтол(Стол):
    """
    Конкретный класс, описывающий деревянный стол.
    """

    def выдержать_вес(self, вес: float) -> bool:
        """
        Проверяет, может ли стол выдержать заданный вес.

        :param вес: Вес в килограммах.
        :return: True, если стол выдержит вес, иначе False.
        """
        return вес <= 100  # Пример: деревянный стол выдерживает до 100 кг

    def изменить_высоту(self, новая_высота: float) -> None:
        """
        Изменяет высоту стола.

        :param новая_высота: Новая высота стола в метрах.
        """
        if новая_высота <= 0:
            raise ValueError("Высота должна быть положительным числом.")
        self.высота = новая_высота


class Дерево(ABC):
    """
    Абстрактный класс, описывающий дерево.
    """

    def __init__(self, вид: str, возраст: int, высота: float):
        """
        Инициализация объекта Дерево.

        :param вид: Вид дерева.
        :param возраст: Возраст дерева в годах.
        :param высота: Высота дерева в метрах.

        :Пример:
        >>> дерево = Дуб("дуб", 50, 20.0)
        >>> дерево.вид
        'дуб'
        """
        if возраст <= 0:
            raise ValueError("Возраст должен быть положительным числом.")
        if высота <= 0:
            raise ValueError("Высота должна быть положительным числом.")

        self.вид = вид
        self.возраст = возраст
        self.высота = высота

    @abstractmethod
    def расти(self, годы: int) -> None:
        """
        Увеличивает возраст и высоту дерева на заданное количество лет.

        :param годы: Количество лет, на которое дерево растет.
        :return: None

        :Пример:
        >>> дерево = Дуб("дуб", 50, 20.0)
        >>> дерево.расти(10)
        >>> дерево.возраст
        60
        """
        ...

    @abstractmethod
    def срубить(self) -> str:
        """
        Срубает дерево и возвращает сообщение о результате.

        :return: Сообщение о том, что дерево срублено.

        :Пример:
        >>> дерево = Дуб("дуб", 50, 20.0)
        >>> дерево.срубить()
        'Дерево срублено'
        """
        ...


class Дуб(Дерево):
    """
    Конкретный класс, описывающий дуб.
    """

    def расти(self, годы: int) -> None:
        """
        Увеличивает возраст и высоту дерева на заданное количество лет.

        :param годы: Количество лет, на которое дерево растет.
        """
        if годы <= 0:
            raise ValueError("Количество лет должно быть положительным числом.")
        self.возраст += годы
        self.высота += годы * 0.5  # Пример: дуб растет на 0.5 метра в год

    def срубить(self) -> str:
        """
        Срубает дерево и возвращает сообщение о результате.

        :return: Сообщение о том, что дерево срублено.
        """
        return "Дерево срублено"


class СоциальнаяСеть(ABC):
    """
    Абстрактный класс, описывающий социальную сеть.
    """

    def __init__(self, название: str, количество_пользователей: int, основатель: Optional[str] = None):
        """
        Инициализация объекта СоциальнаяСеть.

        :param название: Название социальной сети.
        :param количество_пользователей: Количество пользователей в социальной сети.
        :param основатель: Основатель социальной сети (если известен).

        :Пример:
        >>> сеть = Facebook("Facebook", 2000000000, "Марк Цукерберг")
        >>> сеть.название
        'Facebook'
        """
        if количество_пользователей < 0:
            raise ValueError("Количество пользователей не может быть отрицательным.")

        self.название = название
        self.количество_пользователей = количество_пользователей
        self.основатель = основатель

    @abstractmethod
    def добавить_пользователя(self) -> None:
        """
        Увеличивает количество пользователей на 1.

        :return: None

        :Пример:
        >>> сеть = Facebook("Facebook", 2000000000)
        >>> сеть.добавить_пользователя()
        >>> сеть.количество_пользователей
        2000000001
        """
        ...

    @abstractmethod
    def изменить_основателя(self, новый_основатель: str) -> None:
        """
        Изменяет основателя социальной сети.

        :param новый_основатель: Новый основатель социальной сети.
        :return: None

        :Пример:
        >>> сеть = Facebook("Facebook", 2000000000, "Марк Цукерберг")
        >>> сеть.изменить_основателя("Илон Маск")
        >>> сеть.основатель
        'Илон Маск'
        """
        ...


class Facebook(СоциальнаяСеть):
    """
    Конкретный класс, описывающий социальную сеть Facebook.
    """

    def добавить_пользователя(self) -> None:
        """
        Увеличивает количество пользователей на 1.
        """
        self.количество_пользователей += 1

    def изменить_основателя(self, новый_основатель: str) -> None:
        """
        Изменяет основателя социальной сети.

        :param новый_основатель: Новый основатель социальной сети.
        """
        self.основатель = новый_основатель


